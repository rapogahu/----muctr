% Серый Волк, Ниф-Ниф, Наф-Наф и Нуф-Нуф стали филателистами. 
% Каждый из них собирает марки определённой тематики: один — флору, 
% другой — спорт, третий — космос, а Волк — фауну. Вся компания собралась за столом в доме Волка. 
% При этом: Волк сидит слева от Нафа.
% Ниф — справа от того, кто собирает марки про космос.
% Нуф сидит напротив Нафа и при этом совсем не интересуется спортивной тематикой.
% Вопросы:
% Можно ли определить, какие марки собирает каждый из четырёх героев?

тема(фауна). 
тема(флора). 
тема(спорт). 
тема(космос).

место(1). 
место(2). 
место(3). 
место(4).

слева(2, 1).
слева(3, 2).
слева(4, 3).
слева(1, 4).

напротив(1, 3).
напротив(2, 4).
напротив(3, 1).
напротив(4, 2).

решить(Марки_Волка, Марки_Нифа, Марки_Нафа, Марки_Нуфа) :-
    Марки_Волка = фауна,
    тема(Марки_Нифа), 
    тема(Марки_Нафа), 
    тема(Марки_Нуфа),
    Марки_Нифа \= Марки_Волка, 
    Марки_Нифа \= Марки_Нафа, 
    Марки_Нифа \= Марки_Нуфа,
    Марки_Нафа \= Марки_Волка, 
    Марки_Нафа \= Марки_Нуфа,
    Марки_Нуфа \= Марки_Волка,

    Марки_Нуфа \= спорт,
    
    место(Место_Волка),
    место(Место_Нифа),
    место(Место_Нафа),
    место(Место_Нуфа),
    
    Место_Волка \= Место_Нифа, 
    Место_Волка \= Место_Нафа, 
    Место_Волка \= Место_Нуфа,
    Место_Нифа  \= Место_Нафа, 
    Место_Нифа  \= Место_Нуфа,
    Место_Нафа  \= Место_Нуфа,
    
    слева(Место_Волка, Место_Нафа),
    
    напротив(Место_Нуфа, Место_Нафа),
    
    (Марки_Волка = космос -> Место_Космоса = Место_Волка;
     Марки_Нифа  = космос -> Место_Космоса = Место_Нифа;
     Марки_Нафа  = космос -> Место_Космоса = Место_Нафа;
     Марки_Нуфа  = космос -> Место_Космоса = Место_Нуфа),
     
    слева(Место_Космоса, Место_Нифа).

